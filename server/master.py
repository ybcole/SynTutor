"""Loader for the shared SynTutor masterfile (web/content/master.json).

The masterfile is the single table the whole system reads: the rule catalog,
a conceptual explanation ("what this rule governs"), and every quiz question
with its per-item explanation. It is generated by ``npm run build:master`` from
web/js/quiz/{catalog,concepts,s1..s11}.js. The front end imports the same JSON;
this module gives the Python side the same view.

Path resolution: the file lives in ``<repo>/web/content/master.json``. If it is
missing (e.g. before a build), every accessor degrades to empty rather than
raising, so the API keeps working without the concepts attached.
"""

import json
import os
from functools import lru_cache

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
MASTER_PATH = os.path.join(_ROOT, 'web', 'content', 'master.json')


@lru_cache(maxsize=1)
def load_master():
    """Return the parsed masterfile, or an empty skeleton if unavailable."""
    try:
        with open(MASTER_PATH, encoding='utf-8') as handle:
            return json.load(handle)
    except (OSError, ValueError):
        return {
            'sections': [], 'questions': {},
            'ruleCount': 0, 'questionCount': 0, 'quizLength': 5,
        }


@lru_cache(maxsize=1)
def _rules_by_id():
    index = {}
    for section in load_master().get('sections', []):
        for rule in section.get('rules', []):
            entry = dict(rule)
            entry.setdefault('section', section.get('title'))
            entry.setdefault('sectionId', section.get('id'))
            index[rule.get('id')] = entry
    return index


def sections():
    return load_master().get('sections', [])


def rule(rule_id):
    """Catalog entry for a rule (id, rule, example, check, difficulty, concept),
    with its section title/id, or ``None`` if unknown."""
    return _rules_by_id().get(rule_id)


def concept(rule_id):
    """The conceptual explanation of what a rule governs ('' if unknown)."""
    entry = _rules_by_id().get(rule_id)
    return (entry or {}).get('concept', '') or ''


def question_pool(rule_id):
    """Every materialized quiz item for a rule: list of
    ``{bad, good, explanation}``."""
    return load_master().get('questions', {}).get(rule_id, [])


def has_quiz(rule_id):
    return bool(question_pool(rule_id))
