"""Loader for the SynTutor content sheet (web/content/tree_sheet.json).

The sheet is the single table the whole system reads, generated by
``npm run tree:sheet`` (scripts/tree_sheet.py) directly from the model:

  Stage 1  Tokenizer
  Stage 2  POS tagger        (48 lexical tags)
  Stage 3  Constituency parser (24 phrase labels)
  Stage 4  Rule matrix        (111 rules, each with its concept text)

This module gives the Python side (matrix.py XAI) the same view the front end
has. If the file is missing every accessor degrades to empty rather than
raising, so the API keeps working without concepts attached.
"""

import json
import os
from functools import lru_cache

_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
_SHEET_PATH = os.path.join(_ROOT, 'web', 'content', 'tree_sheet.json')
# Legacy location kept as a fallback for older builds.
_LEGACY_PATH = os.path.join(_ROOT, 'web', 'content', 'master.json')


@lru_cache(maxsize=1)
def load_sheet():
    """Return the parsed tree sheet, or an empty skeleton if unavailable."""
    for path in (_SHEET_PATH, _LEGACY_PATH):
        try:
            with open(path, encoding='utf-8') as handle:
                return json.load(handle)
        except (OSError, ValueError):
            continue
    return {'meta': {}, 'stages': []}


@lru_cache(maxsize=1)
def _rules_by_id():
    index = {}
    for stage in load_sheet().get('stages', []):
        for item in stage.get('items', []):
            rid = item.get('rule')
            if not rid:
                continue
            entry = dict(item)
            entry.setdefault('section', stage.get('title'))
            entry.setdefault('sectionId', stage.get('id'))
            # Keep the first constraint's concept; rules repeat across constraints.
            if rid not in index or (not index[rid].get('concept') and entry.get('concept')):
                index[rid] = entry
    return index


def sections():
    return load_sheet().get('stages', [])


def rule(rule_id):
    """Sheet entry for a rule (id, name, example, concept, ...), or ``None``."""
    return _rules_by_id().get(rule_id)


def concept(rule_id):
    """The conceptual explanation of what a rule governs ('' if unknown)."""
    entry = _rules_by_id().get(rule_id)
    return (entry or {}).get('concept', '') or ''
