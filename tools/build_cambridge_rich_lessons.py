#!/usr/bin/env python3
"""Generate rich Cambridge chapter article data in the reviewed lesson style."""
from __future__ import annotations

import json
import sys
from collections import defaultdict
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
sys.path.insert(0, str(ROOT / "server"))
import build_cambridge_lessons_quizzes as base  # noqa: E402

OUT = ROOT / "web/js/cambridge-chapter-data.js"


def title_case(text):
    return " ".join(word[:1].upper() + word[1:] for word in str(text or "").split())


def group(rules, size):
    return [rules[index:index + size] for index in range(0, len(rules), size)]


def build_entry(chapter, rules):
    title = base.TITLES.get(chapter, f"Chapter {chapter}")
    concepts = [base.naturalize(rule.get("concept") or "") for rule in rules if rule.get("concept")]
    topics = [title_case(value) for value in concepts[:4]]
    while len(topics) < 4:
        topics.append(f"{title}: part {len(topics) + 1}")
    first = rules[0]
    second = rules[1] if len(rules) > 1 else rules[0]
    example = base.first_example(first, "correct") or "Read the example together."
    wrong = base.first_example(first, "incorrect") or ""
    intro = (f"{title} brings together {len(rules)} patterns that shape how the rest of the "
             f"sentence fits together. You will meet ideas such as {', '.join(concepts[:4])}. ")
    if wrong:
        intro += f"Each pattern is shown with a sentence that works and a sentence that does not, such as “{example}” and “{wrong}”."
    else:
        intro += f"Each pattern is shown with a clear example, such as “{example}”."
    concepts_blocks = []
    for group_rules in group(rules, 4):
        heading = title_case(group_rules[0].get("concept") or "Pattern")
        paragraph = " ".join(base.rule_sentence(rule) for rule in group_rules)
        concepts_blocks.append([heading, paragraph])
    contrast = [
        "Compare two patterns side by side",
        [
            f"“{base.first_example(first, 'correct')}” shows one pattern: {base.explanation(first)}",
            f"“{base.first_example(second, 'correct')}” shows another: {base.explanation(second)}",
        ],
    ]
    opening = []
    for rule in rules[:2]:
        correct = base.first_example(rule, "correct")
        incorrect = base.first_example(rule, "incorrect")
        if not correct or not incorrect:
            continue
        prompt = f"Which option follows this pattern: {base.naturalize(rule.get('concept') or '')}?"
        opening.append([prompt, [correct, incorrect, f"Neither of these fits {base.naturalize(rule.get('concept') or '')}."], 0])
    apply_example = base.first_example(rules[min(2, len(rules) - 1)], "correct") or example
    apply = [
        ["Check the pattern in your own sentence",
         f"Read your sentence and compare it with “{apply_example}”. Ask which part is doing the work described by the pattern and which part is extra or missing."],
        ["Change only the part that does not fit",
         "If something sounds wrong, change the word or phrase that does not match the pattern. Keep the rest of the sentence as it is, then read it again."],
    ]
    reveal = ["Check your work",
              f"One correct version is “{example}”. The pattern works when {base.explanation(first)}"]
    recap = [title_case(concept) for concept in concepts]
    self_check = [f"Can you explain the pattern behind “{example}” in your own words?",
                  base.explanation(first)]
    return {
        "topics": topics,
        "intro": intro,
        "exampleContext": f"Read this example as one complete sentence. The pattern in focus is {concepts[0] if concepts else title.lower()}.",
        "example": example,
        "introExample": base.explanation(first),
        "preview": [
            f"Find the pattern in “{example}”.",
            f"Compare it with “{base.first_example(second, 'correct')}”.",
            "Apply the same reasoning to a new sentence.",
        ],
        "concepts": concepts_blocks,
        "contrast": contrast,
        "opening": opening,
        "applyExample": apply_example,
        "apply": apply,
        "reveal": reveal,
        "recapSummary": (" ".join(base.rule_sentence(rule) for rule in rules[:4])),
        "recap": recap,
        "selfCheck": self_check,
        "postTestIntro": f"Use the patterns from {title.lower()} to check each answer.",
    }


def main() -> int:
    rules = base.load_rules()
    by_chapter = defaultdict(list)
    for rule in rules:
        chapter = base.chapter_of(rule)
        if chapter:
            by_chapter[chapter].append(rule)
    data = {f"cgel-ch{chapter:02d}": build_entry(chapter, chapter_rules)
            for chapter, chapter_rules in sorted(by_chapter.items())}
    OUT.write_text(
        "// Generated by tools/build_cambridge_rich_lessons.py\n"
        "export const cambridgeChapterData = "
        + json.dumps(data, indent=2, ensure_ascii=False) + ";\n",
        encoding="utf-8")
    print(f"wrote {OUT} ({len(data)} chapters)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
