"""Render immutable Foundations assessment catalog rows, without activating them."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
COURSE = ROOT / 'web/content/lessons/course.json'
TARGET = ROOT / 'supabase/migrations/20261113000001_foundations_catalog.sql'


def render(course):
    def literal(value):
        return "'" + value.replace("'", "''") + "'"

    def key(questions):
        data = {
            question['id']: {
                'position': index,
                'options': [option['id'] for option in question['options']],
                'answer': question['answer'],
            }
            for index, question in enumerate(questions)
        }
        return literal(json.dumps(data, separators=(',', ':'))) + '::jsonb'

    rows = []
    for lesson in course['lessons']:
        assessment = lesson.get('revised_assessment')
        if assessment:
            sections = ','.join(map(literal, assessment['required_sections']))
            rows.append('(' + ','.join([
                literal(lesson['lesson_id']), literal(lesson['content_version']),
                f'array[{sections}]::text[]', key(assessment['opening']), key(assessment['closing']),
            ]) + ')')
    header = '-- Generated by scripts/seed_foundations.py. Does not activate any versions.\n'
    if not rows:
        return header + '-- No revised chapters have been published.\nbegin;\ncommit;\n'
    return (header + 'begin;\ninsert into public.foundation_assessments '
            '(lesson_id,content_version,required_sections,opening,closing) values\n'
            + ',\n'.join(rows)
            + '\non conflict (lesson_id,content_version) do nothing;\ncommit;\n')


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--course', type=Path, default=COURSE)
    args = parser.parse_args()
    print(render(json.loads(args.course.read_text())), end='')
