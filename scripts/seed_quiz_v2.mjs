// Generates supabase/migrations/20261116000002_quiz_v2_catalog.sql from project-approved formal Quiz V2 items.
import fs from 'node:fs';
import { loadActiveCourse, quizCurriculum } from '../web/js/lesson-curriculum.js';
import { makeLessonPractice, validateLessonPractice } from '../web/js/quiz-lesson-practice.js';
import { makeAssessmentItems, validateAssessmentItems } from '../web/js/quiz-assessment-items.js';

const readJson = rel => JSON.parse(fs.readFileSync(new URL('../' + rel, import.meta.url), 'utf8'));
const qSql = v => `'${String(v).replace(/'/g, "''")}'`;

const course = await loadActiveCourse(async p => ({ ok: true, json: async () => readJson('web' + p) }));
const curriculum = quizCurriculum(course);
const syntaxSource = readJson('web/content/quizzes/syntax-practice-source.json');
const practiceItems = validateLessonPractice(makeLessonPractice(curriculum, syntaxSource), curriculum);
const formalItems = validateAssessmentItems(makeAssessmentItems(practiceItems, curriculum), curriculum);

const lines = [
  '-- Generated by scripts/seed_quiz_v2.mjs; seeds project-approved formal Quiz V2 items into public.quiz_items_v1.',
  'begin;',
];

for (const q of formalItems) {
  const optionIds = JSON.stringify(q.options.map(o => o.id));
  lines.push(
    `insert into public.quiz_items_v1 (item_id, content_version, pool_id, answer, option_ids, published) ` +
    `values (${qSql(q.item_id)}, ${qSql(q.content_version)}, ${qSql(q.pool_id)}, ${qSql(q.answer)}, ${qSql(optionIds)}::jsonb, true) ` +
    `on conflict (item_id, content_version) do update set pool_id = excluded.pool_id, answer = excluded.answer, option_ids = excluded.option_ids, published = excluded.published;`
  );
}

lines.push('commit;', '');
const outPath = new URL('../supabase/migrations/20261116000002_quiz_v2_catalog.sql', import.meta.url);
fs.writeFileSync(outPath, lines.join('\n'), 'utf8');
console.log(`Generated ${formalItems.length} quiz_items_v1 rows -> ${outPath.pathname}`);
