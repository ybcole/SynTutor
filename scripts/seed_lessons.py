"""Render a reviewable SQL catalog seed; never connects to a database."""
import json
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
TARGET=ROOT/'supabase/migrations/20261108000001_lesson_catalog.sql'

def render(course=None):
    course=course or json.loads((ROOT/'web/content/lessons/course.json').read_text())
    rows=[]
    for lesson in course['lessons']:
        ident=lesson['lesson_id'];version=lesson['content_version']
        prereqs=json.dumps(lesson['prerequisites'],separators=(',',':')).replace("'","''")
        answers=json.dumps({key:lesson[key]['answer'] for key in ['predict','guided','transfer','exit']},separators=(',',':'))
        rows.append(f"('{ident}','{version}','{prereqs}'::jsonb,'{answers}'::jsonb,true)")
    return '''-- M4 published lesson contract. Generated by scripts/seed_lessons.py.
-- Content changes require a NEW version; never silently change its answer key.
begin;
insert into public.lesson_catalog (lesson_id,content_version,prerequisites,answer_key,published) values
'''+',\n'.join(rows)+'''\non conflict (lesson_id,content_version) do nothing;
commit;
'''
if __name__=='__main__': TARGET.write_text(render());print(TARGET.relative_to(ROOT))
