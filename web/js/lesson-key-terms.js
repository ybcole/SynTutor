export function addLessonKeyTerms(body, el, lessonId, terms = lessonKeyTerms[lessonId]) {
  if (!terms) return;
  const section = el('section', undefined, 'lesson-key-terms');
  section.append(el('h3', 'Key terms'));
  const list = el('dl');
  for (const [term, definition] of terms) {
    const entry = el('div');
    entry.append(el('dt', term), el('dd', definition));
    list.append(entry);
  }
  section.append(list);
  body.append(section);
}
